import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import ts from "typescript";
const source = readFileSync(new URL("../lib/week-workspace.ts",import.meta.url),"utf8");
const compiled = ts.transpileModule(source,{compilerOptions:{module:ts.ModuleKind.ESNext,target:ts.ScriptTarget.ES2022}}).outputText;
const { planDays, movePreview, snapshotOf, weekSelectionSummary } = await import(`data:text/javascript;base64,${Buffer.from(compiled).toString("base64")}`);
assert.deepEqual(planDays("2026-12-28").map(day=>day.value),["2026-12-28","2026-12-29","2026-12-30","2026-12-31","2027-01-01","2027-01-02","2027-01-03"]);
assert.equal(planDays("2028-02-28")[1].value,"2028-02-29");
assert.deepEqual(planDays("not-a-date"),[]);
const items=[{id:"b",template_id:"template-b",scheduled_date:"2026-10-01",status:"planned"},{id:"a",template_id:"template-a",scheduled_date:"2026-10-02",status:"planned"},{id:"c",template_id:null,scheduled_date:"2026-10-03",status:"completed"}];
assert.equal(movePreview(items,"b","2026-10-02").swaps,true);
assert.equal(movePreview(items,"b","2026-10-04").swaps,false);
assert.equal(movePreview(items,"b","2026-10-03"),null);
assert.equal(movePreview(items,"c","2026-10-04"),null);
assert.equal(movePreview(items,"missing","2026-10-04"),null);
assert.deepEqual(snapshotOf(items).map(item=>item.id),["a","b","c"]);
assert.equal(items[0].id,"b");
assert.notDeepEqual(snapshotOf(items),snapshotOf(items.map(item=>item.id==="b"?{...item,template_id:"replacement-template"}:item)));
const plan={generation_method:'reviewed_portfolio_v3',adaptation_summary:'Legacy claim about a balanced portfolio'};
assert.match(weekSelectionSummary(plan,[{template_id:null}]),/No activity template was selected/);
assert.ok(!weekSelectionSummary(plan,[{template_id:null}]).includes('balanced portfolio'));
assert.match(weekSelectionSummary(plan,[]),/No opportunities are stored/);
assert.match(weekSelectionSummary(plan,[{template_id:'fixture'}]),/exact-version review/);
assert.equal(weekSelectionSummary({...plan,generation_method:'historical'},[]),plan.adaptation_summary);
console.log("Week workspace checks passed: date boundaries, leap year, swap preview, recorded-day protection, missing item, stable nonmutating snapshot.");
