import assert from 'node:assert/strict';
export async function checkProfileCreationSql(db,{owner,other,viewer,family}) {
  const one=async(sql,args=[])=>(await db.query(sql,args)).rows[0];
  const login=async id=>db.query("select set_config('request.jwt.claim.sub',$1,false)",[id]);
  const uuid=async()=>(await one('select gen_random_uuid() id')).id;
  await db.exec('reset role');
  const originalPlans=(await db.query('select to_jsonb(p) row from public.plans p order by id')).rows;
  const originalItems=(await db.query('select to_jsonb(i) row from public.activity_instances i order by id')).rows;
  const fresh=await uuid(),request=await uuid(),otherRequest=await uuid();
  await db.query("insert into auth.users(id,email) values($1,'new-family@example.invalid')",[fresh]);
  const create=(key=request,name='Synthetic new family',nick='बच्चा / طفل',year=2024,month=1)=>one('select public.create_family_with_child_checked($1,$2,$3,$4,$5) id',[key,name,nick,year,month]);
  await login(fresh);await db.exec("set time zone 'Pacific/Honolulu'; set role authenticated");
  const today=(await one("select (now() at time zone 'UTC')::date::text d")).d;
  const y=Number(today.slice(0,4)),m=Number(today.slice(5,7));
  for(const args of [[request,' ', 'Child'],[request,'Family',null],[request,'Family','Child',null,1],[request,'Family','Child',2024,null],[null]])await assert.rejects(create(...args),/MIRA_(INVALID|CREATION_REQUEST)/);
  if(m<12)await assert.rejects(create(request,'Future','Child',y,m+1),/MIRA_FUTURE_BIRTH_MONTH/);
  assert.equal((await db.query('select * from public.family_members where user_id=$1',[fresh])).rows.length,0);
  const first=await create(); assert.deepEqual(await create(),first);
  const c=(await one('select id from public.children where family_id=$1',[first.id])).id;
  assert.equal((await db.query('select * from public.children where family_id=$1',[first.id])).rows.length,1);
  await assert.rejects(create(request,'Changed family'),/MIRA_CREATION_REQUEST_CHANGED/);
  await assert.rejects(create(otherRequest),/MIRA_FAMILY_ALREADY_EXISTS/);
  await assert.rejects(db.query("select public.create_family_with_child('Old','Old',2024::smallint,1::smallint)"),e=>e.code==='42501');
  await assert.rejects(db.query("select * from public.profile_creation_requests"),e=>e.code==='42501');
  await assert.rejects(db.query("insert into public.children(family_id,nickname,birth_year,birth_month) values($1,'Bypass',2024,1)",[first.id]),e=>e.code==='42501');
  await db.exec('reset role');await db.query("update public.children set nickname='Later correction',archived_at=now() where id=$1",[c]);
  await db.exec('set role authenticated');assert.deepEqual(await create(),first);
  assert.equal((await one('select nickname from public.children where id=$1',[c])).nickname,'Later correction');
  await db.exec('reset role');await db.query('delete from public.children where id=$1',[c]);
  await db.exec('set role authenticated');await assert.rejects(create(),/MIRA_CREATION_REMOVED/);
  // Additional child: recovery never reapplies active-child changes or edits.
  const addKey=await uuid();
  const add=(key=addKey,nick='Synthetic added child',target=family,year=2024,month=1)=>one('select public.add_child_to_family_checked($1,$2,$3,$4,$5) id',[key,target,nick,year,month]);
  for(const person of [viewer,other]) {await login(person);await assert.rejects(add(),/Caregiver access required/);}
  await login(owner);
  await assert.rejects(db.query("select public.add_child_to_family($1,'Old',2024,1)",[family]),e=>e.code==='42501');
  const added=await add();assert.deepEqual(await add(),added);
  await assert.rejects(add(addKey,'Different child'),/MIRA_CREATION_REQUEST_CHANGED/);
  await assert.rejects(create(addKey),/MIRA_CREATION_REQUEST_CHANGED/);
  await db.query('select public.set_active_child($1)',[added.id]);
  await db.exec('reset role');
  const prior=(await one('select id from public.children where family_id=$1 and id<>$2 and archived_at is null limit 1',[family,added.id])).id;
  await db.query('update public.user_settings set active_child_id=$1 where user_id=$2',[prior,owner]);
  await db.query("update public.children set nickname='New name',archived_at=now() where id=$1",[added.id]);
  await db.exec('set role authenticated');assert.deepEqual(await add(),added);
  assert.equal((await one('select active_child_id from public.user_settings where user_id=$1',[owner])).active_child_id,prior);
  assert.equal((await one('select nickname from public.children where id=$1',[added.id])).nickname,'New name');
  await db.exec('reset role');await db.query('delete from public.children where id=$1',[added.id]);
  await db.exec('set role authenticated');await assert.rejects(add(),/MIRA_CREATION_REMOVED/);
  await db.exec('reset role');await db.query("update public.family_members set role='caregiver' where family_id=$1 and user_id=$2",[family,viewer]);
  await login(viewer);await db.exec('set role authenticated');
  const caregiverKey=await uuid();assert.ok((await add(caregiverKey,'Synthetic caregiver addition')).id);
  const familyToday=(await one('select public.get_family_calendar($1) c',[family])).c.today;
  const fy=Number(familyToday.slice(0,4)),fm=Number(familyToday.slice(5,7));
  if(fm<12)await assert.rejects(add(await uuid(),'Future',family,fy,fm+1),/MIRA_FUTURE_BIRTH_MONTH/);
  await assert.rejects(add(await uuid(),'Null month',family,fy,null),/MIRA_INVALID_BIRTH_CONTEXT/);
  await db.exec('reset role');await db.query("update public.family_members set role='viewer' where family_id=$1 and user_id=$2",[family,viewer]);
  await db.exec('set role authenticated');await assert.rejects(add(caregiverKey,'Synthetic caregiver addition'),/Caregiver access required/);
  await db.exec('reset role; set role anon');
  await assert.rejects(create(),e=>e.code==='42501');await assert.rejects(add(),e=>e.code==='42501');
  await assert.rejects(db.query('select public.validate_birth_context_internal(2024,1,current_date)'),e=>e.code==='42501');
  await db.exec("reset role; set time zone 'UTC'");
  assert.deepEqual((await db.query('select to_jsonb(p) row from public.plans p order by id')).rows,originalPlans);
  assert.deepEqual((await db.query('select to_jsonb(i) row from public.activity_instances i order by id')).rows,originalItems);
  console.log('PASS profile creation SQL: atomic first family, exact retry, changed payload/operation denial, existing membership, null/future dates, additional-child retries, active-child/later-edit preservation, deletion tombstones, role revocation, private receipts, direct/old/anonymous denial and unchanged plans. Local synthetic single-session tests only.');
}
