import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
export async function checkJournalCorrectionsSql(db,{owner,other,viewer,family,child}) {
  const one=async(sql,args=[])=>(await db.query(sql,args)).rows[0];
  const login=id=>db.query("select set_config('request.jwt.claim.sub',$1,false)",[id]);
  await db.exec("reset role; set time zone 'UTC'");await login(owner);
  const plans=(await db.query('select to_jsonb(p) row from public.plans p order by id')).rows;
  const instances=(await db.query('select to_jsonb(i) row from public.activity_instances i order by id')).rows;
  const day=(await one('select public.child_today_internal($1)::text d',[child])).d;
  const request=randomUUID(),args=[request,child,day,'everyday','Original','  原文\nالأصل 🙂  '];
  await db.exec('set role authenticated');
  const id=(await one('select public.create_learning_moment_checked($1,$2,$3,$4,$5,$6) id',args)).id;
  const row=()=>one('select *,updated_at::text version from public.learning_moments where id=$1',[id]);
  const original=await row();
  const edit=(version=original.version,note='  Corrected 原文\nالأصل 🙂  ',date=day,target=child)=>one('select public.update_learning_moment_checked($1,$2,$3,$4,$5,$6,$7) result',[id,target,version,date,'creative','  Corrected title  ',note]);
  const remove=(version=original.version,target=child)=>one('select public.delete_learning_moment_checked($1,$2,$3) removed',[id,target,version]);
  for(const actor of [other,viewer]){await login(actor);await assert.rejects(edit,/Caregiver access required/);await assert.rejects(remove,/Caregiver access required/);}
  await login(owner);
  await assert.rejects(edit(null),/STALE_MOMENT/);await assert.rejects(remove(null),/STALE_MOMENT/);
  await assert.rejects(edit(original.version,' '),/NOTE_INVALID/);
  await assert.rejects(edit(original.version,'x'.repeat(1201)),/NOTE_INVALID/);
  await assert.rejects(edit(original.version,'new','2200-01-01'),/DATE_INVALID/);
  assert.deepEqual(await row(),original);
  const saved=(await edit()).result;assert.ok(saved.updatedAt);
  const corrected=await row();assert.notEqual(corrected.version,original.version);
  assert.equal(corrected.note,'  Corrected 原文\nالأصل 🙂  ');assert.equal(corrected.title,'Corrected title');
  assert.equal(corrected.recorded_by,original.recorded_by);assert.equal(corrected.created_at.getTime(),original.created_at.getTime());
  await assert.rejects(edit(),/STALE_MOMENT/);await assert.rejects(remove(),/STALE_MOMENT/);
  assert.equal((await one('select public.create_learning_moment_checked($1,$2,$3,$4,$5,$6) id',args)).id,id);
  assert.equal((await row()).note,corrected.note);
  await db.exec('reset role');
  const sibling=(await one("insert into public.children(family_id,nickname,birth_year,birth_month) values($1,'Synthetic note sibling',2024,1) returning id",[family])).id;
  await db.query("update public.learning_moments set occurred_on='2000-01-01',updated_at='2000-01-01' where id=$1",[id]);
  const old=await row();assert.ok(Date.parse(old.version)>Date.parse(corrected.version));
  await db.query("update public.family_members set role='caregiver' where user_id=$1 and family_id=$2",[viewer,family]);
  await login(viewer);await db.exec('set role authenticated');
  await assert.rejects(edit(old.version,'new',day,sibling),/NOT_FOUND/);
  await assert.rejects(remove(old.version,sibling),/NOT_FOUND/);
  await edit(old.version,'Old note corrected','2000-01-01');
  const latest=await row();
  await assert.rejects(edit(latest.version,'new','2000-01-02'),/DATE_INVALID/);
  await assert.rejects(db.query('select public.delete_learning_moment($1)',[id]),e=>e.code==='42501');
  await assert.rejects(db.query("update public.learning_moments set note='bypass' where id=$1",[id]),e=>e.code==='42501');
  await assert.rejects(db.query('delete from public.learning_moments where id=$1',[id]),e=>e.code==='42501');
  await db.exec('reset role');await db.query("update public.family_members set role='viewer' where user_id=$1 and family_id=$2",[viewer,family]);
  await db.exec('set role authenticated');await assert.rejects(remove(latest.version),/Caregiver access required/);
  await login(owner);assert.equal((await remove(latest.version)).removed,true);
  await assert.rejects(remove(latest.version),/NOT_FOUND/);
  await assert.rejects(one('select public.create_learning_moment_checked($1,$2,$3,$4,$5,$6)',args),/MIRA_MOMENT_REMOVED/);
  await db.exec('reset role');
  assert.equal((await one('select moment_id from public.learning_moment_requests where user_id=$1 and request_id=$2',[owner,request])).moment_id,null);
  assert.equal((await db.query('select * from public.learning_moments where id=$1',[id])).rows.length,0);
  assert.deepEqual((await db.query('select to_jsonb(p) row from public.plans p order by id')).rows,plans);
  assert.deepEqual((await db.query('select to_jsonb(i) row from public.activity_instances i order by id')).rows,instances);
  await db.exec('set role anon');
  await assert.rejects(edit,e=>e.code==='42501');await assert.rejects(remove,e=>e.code==='42501');
  await assert.rejects(db.query('select public.advance_learning_moment_version_internal()'),e=>e.code==='42501');
  await db.exec('reset role');
  console.log('PASS journal corrections SQL: exact versions, preserved words/author/creation, stale edit/removal, cross-child/family/viewer/anonymous/direct/legacy denial, caregiver correction, original-date retention, private retry tombstone and unchanged plans. Synthetic single-session tests.');
}
